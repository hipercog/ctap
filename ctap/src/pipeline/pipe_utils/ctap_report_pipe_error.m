% A function to report errors
% todo: save the errors into a table which can be easily analyzed. The current version
% produces a very large number of small text files which is impractical.
function ctap_report_pipe_error(ME, crash_root, MC_meas, funStr, step_id)
    % Error handling
    logfile = fullfile(crash_root,...
        sprintf('crashlog_%s.txt', datetime('now','Format',"yyyyMMdd'T'HHmmss")));

    myReport(sprintf([...
        'WARN\n~~~~/#~~~~/#~~~~/#~~~~/#~~~~/#~~~~'...
        '\nProcessing failed on %s \nReason:\n%s\n@ %s : %s'...
        '\n~~~~/#~~~~/#~~~~/#~~~~/#~~~~/#~~~~']...
        , MC_meas.casename...
        , getReport(ME,'extended')...
        , step_id...
        , funStr)...
        , logfile);
end